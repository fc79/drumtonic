"""Write firmware/gen/drum_tables.h: the drum engine's lookup tables (the chip has no FPU, see docs/RULES.md).

  DRUM_SINE[1025]   sin(2 pi i / 1024) in Q15, one extra point for the interpolation
  DRUM_EXP2[257]    2^(i / 256) in Q16: the fraction of an octave for drum_exp2()

    python3 tools/gen_drum_tables.py
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'firmware' / 'gen' / 'drum_tables.h'


def rows(vals, per=12):
    return ',\n'.join('    ' + ', '.join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))


sine = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]
exp2 = [round(65536 * 2 ** (i / 256)) for i in range(257)]

OUT.write_text(f"""/* Generated by tools/gen_drum_tables.py: do not edit. */
#pragma once
#include <stdint.h>

static const int16_t DRUM_SINE[1025] = {{
{rows(sine)}
}};

static const uint32_t DRUM_EXP2[257] = {{
{rows(exp2, 8)}
}};
""")
print(OUT)
