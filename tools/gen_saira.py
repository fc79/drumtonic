"""The FM-1 screen's fonts (graphics B): Saira Condensed 500/700 (SIL OFL 1.1,
assets/fonts/SairaCondensed-OFL.txt) to firmware/gen/saira_font.h, in gfx.c's felucca_font_t format. After
tools/gen_font.py (its TTF path: anti-aliased, tabular figures).

  python3 tools/gen_saira.py            (needs Pillow; run it again only when the sizes or the faces change)

  FONT_LB   16 px Medium   labels, lists, help        FONT_SB   18 px Bold    titles, list rows
  FONT_ST   24 px Bold     the status band            FONT_V    30 px Bold    a knob's value
  FONT_V20  20 px Bold     a value too wide for 30
  FONT_P    48 px Bold     the pattern number (only what it draws)
  FONT_HUGE / FONT_HUGEL  88 px Bold  a knob's value in the bubble while it turns: figures and signs / letters
  FONT_BIG  56 px Bold     the same, when 88 does not fit
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "assets" / "fonts"
OUT = ROOT / "firmware" / "gen" / "saira_font.h"
PAD = 2
SIZES = [("LB", "SairaCondensed-Medium.ttf", 16, 32, 126),
         ("SB", "SairaCondensed-Bold.ttf", 18, 32, 126),
         ("ST", "SairaCondensed-Bold.ttf", 24, 32, 126),
         ("V", "SairaCondensed-Bold.ttf", 30, 32, 126),
         ("V20", "SairaCondensed-Bold.ttf", 20, 32, 126),
         ("P", "SairaCondensed-Bold.ttf", 48, 32, 95),
         ("BIG", "SairaCondensed-Bold.ttf", 56, 32, 95),
         ("HUGE", "SairaCondensed-Bold.ttf", 88, 32, 63),      # (two halves: one font's glyphs must stay under 64 KB)
         ("HUGEL", "SairaCondensed-Bold.ttf", 88, 64, 95)]
KEEP = {"P": " -0123456789>ABCDEFGHIJKLMNOPQRSTUVWXYZ",
        "BIG": " %&+-./0123456789:>ABCDEFGHIJKLMNOPQRSTUVWXYZ",
        "HUGE": " %&+-./0123456789:>",
        "HUGEL": "ABCDEFGHIJKLMNOPQRSTUVWXYZ"}   # the faces drawn with fewer characters than their range


def render(ttf, px, first, last):
    font = ImageFont.truetype(str(FONTS / ttf), px)
    feats = ["tnum"]
    asc, desc = font.getmetrics()
    top = max(0, font.getbbox("A8|(", features=feats)[1] - 1)
    h = asc + desc - top
    glyphs = []
    for c in range(first, last + 1):
        ch = chr(c)
        adv = int(round(font.getlength(ch, features=feats)))
        bw = adv + 2 * PAD
        img = Image.new("L", (bw, asc + desc), 0)
        ImageDraw.Draw(img).text((PAD, 0), ch, font=font, fill=255, features=feats)
        img = img.crop((0, top, bw, top + h))
        glyphs.append((adv, bw, [min(15, (v + 8) // 17) for v in img.tobytes()]))
    return h, glyphs


def main():
    lines = ["/* generated by tools/gen_saira.py: Saira Condensed (SIL OFL 1.1, assets/fonts/SairaCondensed-OFL.txt) */",
             "#pragma once", "#include <stdint.h>", ""]
    total = 0
    for name, ttf, px, first, last in SIZES:
        h, glyphs = render(ttf, px, first, last)
        if name in KEEP:
            glyphs = [g if chr(first + i) in KEEP[name] else (0, 0, []) for i, g in enumerate(glyphs)]
        data, offs = [], []
        for adv, bw, g in glyphs:
            offs.append(len(data))
            for y in range(h):
                row = g[y * bw:(y + 1) * bw] + [0]
                for x in range(0, bw, 2):
                    data.append((row[x] << 4) | row[x + 1])
        assert len(data) < 65536
        total += len(data)
        lines.append(f"static const uint8_t FONT_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint16_t FONT_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        lines.append(f"static const uint8_t FONT_{name}_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _ in glyphs) + "};")
        lines.append(f"static const uint8_t FONT_{name}_BW[{len(glyphs)}] = {{" + ", ".join(str(b) for _, b, _ in glyphs) + "};")
        lines.append(f"static const felucca_font_t FONT_{name} = {{ {h}, {PAD}, {first}, {last}, "
                     f"FONT_{name}_ADV, FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA }};")
        lines.append("")
        print(f"font {name}: {ttf} {px} px, h {h}, digit advance {glyphs[ord('0') - first][0]}, {len(data)} B")
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(ROOT)}: {total} B of glyphs")


if __name__ == "__main__":
    sys.exit(main())
